-- 7. WALLET_FUNDINGS
-- ============================================================
CREATE TABLE IF NOT EXISTS wallet_fundings (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE CASCADE,
  amount numeric(10,2) NOT NULL CHECK (amount > 0),
  reference varchar(100) UNIQUE NOT NULL DEFAULT ('FUND-' || upper(substr(encode(gen_random_bytes(6), 'hex'), 1, 12))),
  status varchar(20) NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'success', 'failed')),
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE wallet_fundings ENABLE ROW LEVEL SECURITY;

CREATE INDEX IF NOT EXISTS idx_wallet_fundings_user ON wallet_fundings(user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_wallet_fundings_status ON wallet_fundings(status);

-- Users can insert and read their own funding requests
DROP POLICY IF EXISTS "select_own_fundings" ON wallet_fundings;
CREATE POLICY "select_own_fundings" ON wallet_fundings FOR SELECT
  TO authenticated USING (auth.uid() = user_id);

DROP POLICY IF EXISTS "insert_own_fundings" ON wallet_fundings;
CREATE POLICY "insert_own_fundings" ON wallet_fundings FOR INSERT
  TO authenticated WITH CHECK (auth.uid() = user_id);

