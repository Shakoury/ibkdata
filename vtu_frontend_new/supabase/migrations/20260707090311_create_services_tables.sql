-- 2. PROVIDER_LOGS
-- ============================================================
CREATE TABLE IF NOT EXISTS provider_logs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider_id bigint NOT NULL REFERENCES providers(id) ON DELETE CASCADE,
  transaction_id uuid REFERENCES transactions(id) ON DELETE CASCADE,
  log_type varchar(20) NOT NULL,
  endpoint varchar(255) NOT NULL DEFAULT '',
  request_data jsonb NOT NULL DEFAULT '{}'::jsonb,
  response_data jsonb NOT NULL DEFAULT '{}'::jsonb,
  status_code integer,
  response_time float NOT NULL DEFAULT 0.0,
  error_message text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE provider_logs ENABLE ROW LEVEL SECURITY;

CREATE INDEX IF NOT EXISTS idx_provider_logs_provider_created ON provider_logs(provider_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_provider_logs_tx ON provider_logs(transaction_id);

-- Staff can read provider logs (no client writes — server-side only)
DROP POLICY IF EXISTS "staff_read_provider_logs" ON provider_logs;
CREATE POLICY "staff_read_provider_logs" ON provider_logs FOR SELECT
  TO authenticated USING (
    EXISTS (SELECT 1 FROM profiles p WHERE p.id = auth.uid() AND p.is_staff = true)
  );

